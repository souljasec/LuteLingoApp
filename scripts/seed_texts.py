"""Generate migrations/0002_seed_texts.sql from the lute-custom content scripts (school texts for everyone).

Usage: python3 -I scripts/seed_texts.py path/to/content > migrations/0002_seed_texts.sql
"""
import csv, os, subprocess, sys, tempfile

src = os.path.expanduser(sys.argv[1])
q = lambda s: "'" + s.replace("'", "''") + "'"
print("-- School texts for everyone. Generated by scripts/seed_texts.py from lute-custom/content.")
for name in ["north.py", "bacho.py", "world.py"]:
    with tempfile.TemporaryDirectory() as d:
        out = os.path.join(d, "t.csv")
        subprocess.run([sys.executable, "-I", os.path.join(src, name), out], check=True, capture_output=True)
        for row in csv.DictReader(open(out)):
            print(f"INSERT INTO texts (title, body, visibility) VALUES ({q(row['title'])}, {q(row['text'])}, 'all');")
